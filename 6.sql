SELECT * FROM ALUNOS;

SELECT * FROM MATERIAS;

SELECT * FROM MATRICULA;

SELECT
    A.NOME AS ALUNO,
    C.NOME AS CURSO,
    M.NOME AS MATERIA,
    MT.PERLETIVO,
    MT.N1,
    MT.N2,
    MT.N3,
    MT.N4,
    MT.MEDIA,
    MT.TOTALFALTAS,
    MT.PERCFREQ,
    MT.NOTAEXAME,
    MT.MEDIAFINAL,
    MT.RESULTADO
FROM MATRICULA MT
INNER JOIN ALUNOS A
    ON MT.MATRICULA = A.MATRICULA
INNER JOIN CURSOS C
    ON MT.CURSO = C.CURSO
INNER JOIN MATERIAS M
    ON MT.MATERIA = M.SIGLA;