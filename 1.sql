CREATE DATABASE IF NOT EXISTS Universidade;

USE Universidade;

CREATE TABLE ALUNOS (
    MATRICULA INT NOT NULL AUTO_INCREMENT,
    NOME VARCHAR(50) NOT NULL,
    PRIMARY KEY (MATRICULA)
);

CREATE TABLE CURSOS (
    CURSO CHAR(3) NOT NULL,
    NOME VARCHAR(50) NOT NULL,
    PRIMARY KEY (CURSO)
);

CREATE TABLE PROFESSOR (
    PROFESSOR INT NOT NULL AUTO_INCREMENT,
    NOME VARCHAR(50) NOT NULL,
    PRIMARY KEY (PROFESSOR)
);

CREATE TABLE MATERIAS (
    SIGLA CHAR(3) NOT NULL,
    NOME VARCHAR(50) NOT NULL,
    CARGAHORARIA INT NOT NULL,
    CURSO CHAR(3) NOT NULL,
    PROFESSOR INT,
    PRIMARY KEY (SIGLA),

    FOREIGN KEY (CURSO)
        REFERENCES CURSOS (CURSO),

    FOREIGN KEY (PROFESSOR)
        REFERENCES PROFESSOR (PROFESSOR)
);

CREATE TABLE MATRICULA (
    MATRICULA INT NOT NULL,
    CURSO CHAR(3) NOT NULL,
    MATERIA CHAR(3) NOT NULL,
    PROFESSOR INT,
    PERLETIVO INT NOT NULL,

    N1 DECIMAL(4,2),
    N2 DECIMAL(4,2),
    N3 DECIMAL(4,2),
    N4 DECIMAL(4,2),

    TOTALPONTOS DECIMAL(5,2),
    MEDIA DECIMAL(4,2),

    F1 INT,
    F2 INT,
    F3 INT,
    F4 INT,

    TOTALFALTAS INT,
    PERCFREQ DECIMAL(5,2),
    RESULTADO VARCHAR(20),

    MEDIAFINAL DECIMAL(4,2),
    NOTAEXAME DECIMAL(4,2),

    PRIMARY KEY (
        MATRICULA,
        CURSO,
        MATERIA,
        PERLETIVO
    ),

    FOREIGN KEY (MATRICULA)
        REFERENCES ALUNOS (MATRICULA),

    FOREIGN KEY (CURSO)
        REFERENCES CURSOS (CURSO),

    FOREIGN KEY (MATERIA)
        REFERENCES MATERIAS (SIGLA),

    FOREIGN KEY (PROFESSOR)
        REFERENCES PROFESSOR (PROFESSOR)
);