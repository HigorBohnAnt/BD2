USE Universidade;
DROP PROCEDURE IF EXISTS sp_LancaExame;

DELIMITER //

CREATE PROCEDURE sp_LancaExame (
    IN p_MATRICULA INT,
    IN p_CURSO CHAR(3),
    IN p_MATERIA CHAR(3),
    IN p_PERLETIVO INT,
    IN p_NOTAEXAME DECIMAL(4,2)
)
BEGIN
    DECLARE v_MEDIA DECIMAL(4,2);
    DECLARE v_RESULTADO VARCHAR(20);
    DECLARE v_MEDIAFINAL DECIMAL(4,2);

    SELECT MEDIA, RESULTADO
    INTO v_MEDIA, v_RESULTADO
    FROM MATRICULA
    WHERE MATRICULA = p_MATRICULA
      AND CURSO = p_CURSO
      AND MATERIA = p_MATERIA
      AND PERLETIVO = p_PERLETIVO;

    IF v_RESULTADO = 'EXAME' THEN

        SET v_MEDIAFINAL = (v_MEDIA + p_NOTAEXAME) / 2;

        IF v_MEDIAFINAL >= 5 THEN
            UPDATE MATRICULA
            SET NOTAEXAME = p_NOTAEXAME,
                MEDIAFINAL = v_MEDIAFINAL,
                RESULTADO = 'APROVADO'
            WHERE MATRICULA = p_MATRICULA
              AND CURSO = p_CURSO
              AND MATERIA = p_MATERIA
              AND PERLETIVO = p_PERLETIVO;
        ELSE
            UPDATE MATRICULA
            SET NOTAEXAME = p_NOTAEXAME,
                MEDIAFINAL = v_MEDIAFINAL,
                RESULTADO = 'REPROVADO'
            WHERE MATRICULA = p_MATRICULA
              AND CURSO = p_CURSO
              AND MATERIA = p_MATERIA
              AND PERLETIVO = p_PERLETIVO;
        END IF;

    END IF;

    SELECT *
    FROM MATRICULA
    WHERE MATRICULA = p_MATRICULA
      AND CURSO = p_CURSO
      AND MATERIA = p_MATERIA
      AND PERLETIVO = p_PERLETIVO;

END //

DELIMITER ;