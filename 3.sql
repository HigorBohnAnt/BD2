USE Universidade;
DROP PROCEDURE IF EXISTS procMATRICULAALUNO;

DELIMITER //

CREATE PROCEDURE procMATRICULAALUNO (
    IN p_NOME VARCHAR(50),
    IN p_CURSO CHAR(3)
)
BEGIN
    DECLARE v_MATRICULA INT;

    INSERT INTO ALUNOS (NOME)
    VALUES (p_NOME);

    SET v_MATRICULA = LAST_INSERT_ID();

    INSERT INTO MATRICULA (
        MATRICULA,
        CURSO,
        MATERIA,
        PROFESSOR,
        PERLETIVO
    )
    SELECT
        v_MATRICULA,
        MATERIAS.CURSO,
        MATERIAS.SIGLA,
        MATERIAS.PROFESSOR,
        2025
    FROM MATERIAS
    WHERE MATERIAS.CURSO = p_CURSO;

END //

DELIMITER ;